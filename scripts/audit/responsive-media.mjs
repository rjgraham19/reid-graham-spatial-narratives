import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import sharp from 'sharp';
const records=JSON.parse(await fs.readFile('audit/media-insets.json','utf8'));
await fs.mkdir('public/optimized',{recursive:true});
const imports=[],entries=[],report=[];
for(const [index,r] of records.entries()) {
  if(r.bytes<80000)continue;
  const hash=crypto.createHash('sha256').update(await fs.readFile(r.file)).digest('hex').slice(0,12);
  const widths=[...new Set([320,640,1280,2560].map(w=>Math.min(w,r.width)))];
  const variants=[];
  for(const width of widths){const url=`/optimized/${hash}-${width}.webp`;const dest=`public${url}`;
    try {await fs.access(dest)} catch {await sharp(r.file).resize({width,withoutEnlargement:true}).webp({quality:88,effort:5}).toFile(dest)}
    variants.push({url,width,bytes:(await fs.stat(dest)).size});
  }
  const key=r.file.startsWith('src/')?`image${index}`:JSON.stringify('/'+r.file.slice(7));
  if(r.file.startsWith('src/'))imports.push(`import image${index} from ${JSON.stringify('@/'+r.file.slice(4))};`);
  entries.push(`[${key}]: {src:${JSON.stringify(variants.at(-1).url)},srcSet:${JSON.stringify(variants.map(v=>`${v.url} ${v.width}w`).join(', '))}},`);
  report.push({...r,variants});
}
await fs.writeFile('src/lib/responsive-media.ts',`// Generated by scripts/audit/responsive-media.mjs; originals are preserved.\n${imports.join('\n')}\nconst variants:Record<string,{src:string;srcSet:string}>={\n${entries.join('\n')}\n};\nexport function responsiveMedia(src:string|undefined,sizes='(max-width: 767px) calc(100vw - 48px), (max-width: 1555px) 90vw, 1400px'){return src&&variants[src]?{...variants[src],sizes}:{};}\n`);
await fs.writeFile('audit/responsive-media.json',JSON.stringify(report,null,2));
console.log(`Generated responsive WebP for ${report.length} images.`);
