import sharp from 'sharp';
import fs from 'node:fs/promises';
import path from 'node:path';
const roots=['src/assets/rg','public/design-media'];
const files=[];
async function walk(dir){for(const e of await fs.readdir(dir,{withFileTypes:true})){const p=`${dir}/${e.name}`;if(e.isDirectory())await walk(p);else if(/\.(png|jpe?g|webp|avif)$/i.test(p))files.push(p)}}
for(const root of roots)await walk(root);
const records=[];
for(const file of files){
  const meta=await sharp(file).metadata();
  const {data,info}=await sharp(file).resize({width:800,height:800,fit:'inside',withoutEnlargement:true}).removeAlpha().raw().toBuffer({resolveWithObject:true});
  const {width:w,height:h,channels:c}=info;
  const lum=(x,y)=>{const i=(y*w+x)*c;return .2126*data[i]+.7152*data[i+1]+.0722*data[i+2]};
  const edges=[];for(let x=0;x<w;x++){edges.push(lum(x,0),lum(x,h-1))}for(let y=0;y<h;y++)edges.push(lum(0,y),lum(w-1,y));
  const black=edges.filter(x=>x<12).length/edges.length,white=edges.filter(x=>x>243).length/edges.length;
  const background=black>.55?'black':white>.55?'white':'none';
  let left=0,right=w-1,top=0,bottom=h-1;
  if(background!=='none'){
    const xs=new Uint32Array(w),ys=new Uint32Array(h);
    for(let y=0;y<h;y++)for(let x=0;x<w;x++){const l=lum(x,y);if(background==='black'?l>=16:l<=239){xs[x]++;ys[y]++}}
    // Require a small run of real pixels, rather than a lone JPEG speck.
    const validX=[...xs.keys()].filter(x=>xs[x]>=Math.max(3,h*.003));
    const validY=[...ys.keys()].filter(y=>ys[y]>=Math.max(3,w*.003));
    if(validX.length&&validY.length){left=validX[0];right=validX.at(-1);top=validY[0];bottom=validY.at(-1)}
  }
  records.push({file,width:meta.width,height:meta.height,bytes:(await fs.stat(file)).size,background,insets:{top:top/h,right:(w-1-right)/w,bottom:(h-1-bottom)/h,left:left/w}});
}
await fs.mkdir('audit',{recursive:true});
await fs.writeFile('audit/media-insets.json',JSON.stringify(records,null,2));
const imports=records.filter(r=>r.file.startsWith('src/')).map((r,i)=>`import image${i} from ${JSON.stringify('@/'+r.file.slice(4))};`);
let i=0;
const entries=records.map(r=>`  [${r.file.startsWith('src/')?`image${i++}`:JSON.stringify('/'+r.file.slice(7))}]: ${JSON.stringify({width:r.width,height:r.height,background:r.background,insets:r.insets})},`);
await fs.writeFile('src/lib/media-insets.ts',`// Generated by scripts/audit/media-insets.mjs. Insets are fractions, not pixels.\n${imports.join('\n')}\nexport const mediaInsets: Record<string, {width:number;height:number;background:string;insets:{top:number;right:number;bottom:number;left:number}}> = {\n${entries.join('\n')}\n};\n`);
console.log(`Scanned ${records.length} images; ${records.filter(r=>r.background!=='none').length} have uniform edge backgrounds.`);
